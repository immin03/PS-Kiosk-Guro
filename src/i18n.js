export function detectLang() {
  try {
    const q = new URLSearchParams(window.location.search).get("lang");
    if (q && STRINGS[q]) return q;
    const saved = localStorage.getItem("ps_lang");
    if (saved && STRINGS[saved]) return saved;
  } catch (_) {}
  return "ko";
}

export function persistLang(lang) {
  try { localStorage.setItem("ps_lang", lang); } catch (_) {}
}

export function t(lang, key, vars) {
  const dict = STRINGS[lang] || STRINGS.ko;
  let s = dict[key] ?? STRINGS.ko[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = String(s).split("{" + k + "}").join(String(v));
    }
  }
  return s;
}

export function sectionLabel(lang, rack) {
  if (!rack) return "";
  const key = "section." + String(rack).split(/[,·~]/)[0].trim();
  return t(lang, key);
}

export function catLabel(lang, cat) {
  if (!cat) return "";
  const byId = t(lang, "cat." + cat.id);
  if (byId && byId !== "cat." + cat.id) return byId;
  return sectionLabel(lang, cat.racks) || cat.name;
}

export function zoneLabel(lang, zoneId) {
  return t(lang, "zone." + zoneId);
}

export function topCatLabel(lang, type) {
  return t(lang, "top." + type);
}

export function topCatSub(lang, type) {
  return t(lang, "top." + type + ".sub");
}
